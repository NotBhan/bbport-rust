#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_error_codes_follow_the_base_offsets() {
        assert_eq!(
            ORBIS_NET_ERROR_EPERM,
            ORBIS_NET_ERROR_BASE + ORBIS_NET_EPERM
        );
        assert_eq!(ORBIS_NET_ERROR_EAGAIN, ORBIS_NET_ERROR_EWOULDBLOCK);
        assert_eq!(ORBIS_NET_EWOULDBLOCK, ORBIS_NET_EAGAIN);
        assert_eq!(ORBIS_NET_ENOTSUP, ORBIS_NET_EOPNOTSUPP);
        assert_eq!(ORBIS_NET_ERROR_ENOALLOCMEM, 0x804101ceu32 as i32);
        assert_eq!(ORBIS_NET_ERROR_RESOLVER_ENOTINIT, 0x804101ecu32 as i32);
    }
}
