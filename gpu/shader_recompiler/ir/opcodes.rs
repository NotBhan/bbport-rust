/// `Shader::IR::Detail::CalculateNumArgsOf`, evaluated over the table.
const fn calculate_num_args(index: usize) -> u8 {
    let arg_types = META_TABLE[index].arg_types;
    let mut i = 0;
    while i < 6 {
        if arg_types[i].bits() == Type::Void.bits() {
            return i as u8;
        }
        i += 1;
    }
    6
}

/// `Shader::IR::Detail::NUM_ARGS`.
const NUM_ARGS: [u8; OPCODE_COUNT] = {
    let mut counts = [0u8; OPCODE_COUNT];
    let mut i = 0;
    while i < OPCODE_COUNT {
        counts[i] = calculate_num_args(i);
        i += 1;
    }
    counts
};

