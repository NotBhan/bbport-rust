#[cfg(test)]
mod tests {
    use super::*;

    const PRINTABLE: [Opcode; 4] = [
        Opcode::Phi,
        Opcode::DebugPrint,
        Opcode::ReadConst,
        Opcode::GroupAny,
    ];

    #[test]
    fn the_table_has_a_row_per_opcode() {
        assert_eq!(Opcode::ALL.len(), 415);
        assert_eq!(Opcode::Void.index(), 1);
        assert_eq!(Opcode::ALL[Opcode::GroupAny.index()], Opcode::GroupAny);
        assert_eq!(Opcode::ALL[Opcode::Memtime.index()], Opcode::Memtime);
        assert_eq!(MAGIC_ENUM_MIN, Opcode::Phi);
        assert_eq!(MAGIC_ENUM_MAX, Opcode::GroupAny);
        assert_eq!(Opcode::Memtime.index(), 414, "the table's last row");
    }

    #[test]
    fn names_come_back_from_the_table() {
        assert_eq!(name_of(Opcode::Phi), "Phi");
        assert_eq!(name_of(Opcode::DebugPrint), "DebugPrint");
        assert_eq!(name_of(Opcode::ReadConst), "ReadConst");
        assert_eq!(name_of(Opcode::GroupAny), "GroupAny");
        assert_eq!(Opcode::Memtime.name(), "Memtime");
        for op in Opcode::ALL {
            assert!(!op.name().is_empty(), "{op:?}");
        }
    }

    #[test]
    fn return_and_argument_types_match_the_inc() {
        assert_eq!(type_of(Opcode::Phi), Type::Opaque);
        assert_eq!(type_of(Opcode::Void), Type::Void);
        assert_eq!(type_of(Opcode::Memtime), Type::U64);
        assert_eq!(type_of(Opcode::DebugPrint), Type::Void);
        assert_eq!(arg_type_of(Opcode::DebugPrint, 0), Type::StringLiteral);
        assert_eq!(arg_type_of(Opcode::DebugPrint, 1), Type::Opaque);
        assert_eq!(arg_type_of(Opcode::ReadConst, 0), Type::U32x2);
        assert_eq!(arg_type_of(Opcode::DataAppend, 1), Type::U1);
        assert_eq!(arg_type_of(Opcode::GroupAny, 0), Type::U1);
    }

    #[test]
    fn the_argument_counts_follow_the_void_terminator() {
        assert_eq!(num_args_of(Opcode::DebugPrint), 5);
        assert_eq!(num_args_of(Opcode::Phi), 0);
        assert_eq!(num_args_of(Opcode::Void), 0);
        assert_eq!(num_args_of(Opcode::ReadConst), 2);
        assert_eq!(num_args_of(Opcode::DataAppend), 2);
        // Every row lists its arguments first and pads with Void, which is what the C++'s
        // CalculateNumArgsOf relies on.
        for op in Opcode::ALL {
            let count = op.num_args();
            assert!(count <= 6, "{op:?}");
            for index in 0..count {
                assert_ne!(op.arg_type(index), Type::Void, "{op:?} arg {index}");
            }
            for index in count..6 {
                assert_eq!(op.arg_type(index), Type::Void, "{op:?} arg {index}");
            }
        }
        for op in PRINTABLE {
            assert!(op.num_args() <= 5);
        }
    }
}
