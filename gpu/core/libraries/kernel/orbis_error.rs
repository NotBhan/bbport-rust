mod tests {
    use super::*;

    #[test]
    fn the_codes_match_the_header() {
        assert_eq!(ORBIS_KERNEL_ERROR_UNKNOWN, 0x80020000u32 as i32);
        assert_eq!(ORBIS_KERNEL_ERROR_EWOULDBLOCK, ORBIS_KERNEL_ERROR_EAGAIN);
        assert_eq!(ORBIS_KERNEL_ERROR_ENOTSUP, ORBIS_KERNEL_ERROR_EOPNOTSUPP);
        assert_eq!(ORBIS_KERNEL_ERROR_ESTART, 0x80020064u32 as i32);
    }
}
