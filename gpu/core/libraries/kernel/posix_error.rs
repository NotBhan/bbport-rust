#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_codes_match_the_header() {
        assert_eq!(POSIX_EPERM, 1);
        assert_eq!(POSIX_EAGAIN, POSIX_EWOULDBLOCK);
        assert_eq!(POSIX_ENOTSUP, POSIX_EOPNOTSUPP);
        assert_eq!(POSIX_ELAST, POSIX_EINVALID2MB);
        assert_eq!(POSIX_ETIME, 1074);
    }
}
