/// `macro_tile_extents`, indexed by samples_log then row*5+column.
pub const MACRO_TILE_EXTENTS: [[[u32; 2]; 135]; 4] = [
    MACRO_TILE_EXTENTS_X1,
    MACRO_TILE_EXTENTS_X2,
    MACRO_TILE_EXTENTS_X4,
    MACRO_TILE_EXTENTS_X8,
];

/// `macro_tile_extents_alt`.
pub const MACRO_TILE_EXTENTS_ALT: [[[u32; 2]; 135]; 4] = [
    MACRO_TILE_EXTENTS_ALT_X1,
    MACRO_TILE_EXTENTS_ALT_X2,
    MACRO_TILE_EXTENTS_ALT_X4,
    MACRO_TILE_EXTENTS_ALT_X8,
];

/// `GetMacroTileExtents`.
pub fn get_macro_tile_extents(
    tile_mode: TileMode,
    bpp: u32,
    num_samples: u32,
    alt: bool,
) -> (u32, u32) {
    assert!(num_samples <= 8, "num_samples must be at most 8");
    let samples_log = num_samples.trailing_zeros() as usize;
    let row = tile_mode.raw() as usize * 5;
    let column = (32 - bpp.leading_zeros() - 4) as usize;
    let table = if alt {
        &MACRO_TILE_EXTENTS_ALT
    } else {
        &MACRO_TILE_EXTENTS
    };
    let [width, height] = table[samples_log][row + column];
    (width, height)
}

fn plane_bytes(pitch: u32, height: u32, bpp: u32, num_samples: u32) -> usize {
    (pitch as usize * height as usize * bpp as usize * num_samples as usize).div_ceil(8)
}

/// `ImageSizeLinearAligned`.
pub fn image_size_linear_aligned(
    pitch: u32,
    height: u32,
    bpp: u32,
    num_samples: u32,
) -> (u32, u32, usize) {
    let pitch_align = 8u32.max(64 / bpp.div_ceil(8));
    let mut pitch_aligned = (pitch + pitch_align - 1) & !(pitch_align - 1);
    let height_aligned = height;
    let mut log_size = pitch_aligned as usize * height_aligned as usize * num_samples as usize;
    let slice_align = 64u32.max(256 / bpp.div_ceil(8));
    while !log_size.is_multiple_of(slice_align as usize) {
        pitch_aligned += pitch_align;
        log_size = pitch_aligned as usize * height_aligned as usize * num_samples as usize;
    }
    (
        pitch_aligned,
        height_aligned,
        (log_size * bpp as usize).div_ceil(8),
    )
}

/// `ImageSizeMicroTiled`.
pub fn image_size_micro_tiled(
    pitch: u32,
    height: u32,
    thickness: u32,
    bpp: u32,
    num_samples: u32,
) -> (u32, u32, usize) {
    let (pitch_align, height_align) = MICRO_TILE_EXTENT;
    let mut pitch_aligned = (pitch + pitch_align - 1) & !(pitch_align - 1);
    let height_aligned = (height + height_align - 1) & !(height_align - 1);
    let mut log_size = plane_bytes(pitch_aligned, height_aligned, bpp, num_samples);
    while !((log_size as u32) * thickness).is_multiple_of(256) {
        pitch_aligned += pitch_align;
        log_size = plane_bytes(pitch_aligned, height_aligned, bpp, num_samples);
    }
    (pitch_aligned, height_aligned, log_size)
}

/// `ImageSizeMacroTiled`.
#[allow(clippy::too_many_arguments)]
pub fn image_size_macro_tiled(
    pitch: u32,
    height: u32,
    thickness: u32,
    bpp: u32,
    num_samples: u32,
    tile_mode: TileMode,
    mip_n: u32,
    alt: bool,
) -> (u32, u32, usize) {
    let (pitch_align, height_align) = get_macro_tile_extents(tile_mode, bpp, num_samples, alt);
    assert!(pitch_align != 0 && height_align != 0);
    if mip_n > 0 && (pitch < pitch_align || height < height_align) {
        return image_size_micro_tiled(pitch, height, thickness, bpp, num_samples);
    }
    let pitch_aligned = (pitch + pitch_align - 1) & !(pitch_align - 1);
    let height_aligned = (height + height_align - 1) & !(height_align - 1);
    let log_size = pitch_aligned as usize * height_aligned as usize * num_samples as usize;
    (
        pitch_aligned,
        height_aligned,
        (log_size * bpp as usize).div_ceil(8),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_macro_tile_extents_match_the_tables() {
        assert_eq!(
            get_macro_tile_extents(TileMode::Depth2DThin64, 8, 1, false),
            (256, 128)
        );
        assert_eq!(
            get_macro_tile_extents(TileMode::Thick2DXThick, 128, 8, false),
            (64, 64)
        );
        assert_eq!(
            get_macro_tile_extents(TileMode::Depth2DThin64, 8, 1, true),
            (256, 128)
        );
        assert_eq!(
            get_macro_tile_extents(TileMode::Thick3DXThick, 128, 8, true),
            (128, 64)
        );
        assert_eq!(MACRO_TILE_EXTENTS.len(), 4);
        assert_eq!(MACRO_TILE_EXTENTS[0].len(), 135);
    }

    #[test]
    fn the_linear_size_aligns_the_pitch_and_slice() {
        assert_eq!(image_size_linear_aligned(100, 10, 32, 1), (128, 10, 5120));
        assert_eq!(image_size_linear_aligned(64, 8, 32, 1), (64, 8, 2048));
    }

    #[test]
    fn the_micro_tiled_size_aligns_and_pads_to_256() {
        assert_eq!(image_size_micro_tiled(100, 10, 1, 32, 1), (104, 16, 6656));
        assert_eq!(image_size_micro_tiled(64, 8, 1, 32, 1), (64, 8, 2048));
    }

    #[test]
    fn the_macro_tiled_size_downgrades_small_mips() {
        let (pitch, height, _) =
            image_size_macro_tiled(2048, 1024, 1, 32, 1, TileMode::Thin2DThin, 0, false);
        assert_eq!((pitch, height), (2048, 1024));
        let (pitch, height, size) =
            image_size_macro_tiled(64, 64, 1, 32, 1, TileMode::Thin2DThin, 1, false);
        assert_eq!((pitch, height, size), (64, 64, 16384));
    }
}
